// ==========================================
document.addEventListener(
    "DOMContentLoaded",
    () => {

        // Initial Render
        renderAlbums();

        // Back to Albums
        if (backToAlbums) {

            backToAlbums.addEventListener(
                "click",
                renderAlbums
            );
        }

        // Keyboard Shortcuts for Presentation
        document.addEventListener(
            "keydown",
            (e) => {

                if (
                    presOverlay &&
                    presOverlay.style.display === "flex"
                ) {

                    if (
                        e.key === "ArrowRight" ||
                        e.key === " "
                    ) {
                        nextSlide(e);
                    }

                    if (
                        e.key === "ArrowLeft"
                    ) {
                        prevSlide(e);
                    }

                    if (
                        e.key === "b" ||
                        e.key === "B"
                    ) {
                        togglePlayPause();
                    }

                    if (
                        e.key === "f" ||
                        e.key === "F"
                    ) {
                        toggleFullscreen();
                    }

                    if (
                        e.key === "Escape" &&
                        !document.fullscreenElement
                    ) {
                        exitPresentation();
                    }
                }
            }
        );
    }
);
